public class Integer {
    public static void main(String[] args) {
        int x = 12;
        int y = 16; 
        int z = 32;
        System.out.println("x+y");
        System.out.println(x+y);
        System.out.println(x+y+z);
        System.out.println(x-y);
        System.out.println(x*y);
        System.out.println(x/y);
    }
}
