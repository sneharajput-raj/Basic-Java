public class CharFloatDouble {
    public static void main(String[] args) {
        char ch = 'A';
        System.out.println("ch");
        System.out.println(ch);
        System.out.println(ch + ch);
        System.out.println();

        float x = 764;
        float y = 55;
        System.out.println(x*y);
        System.out.println(x/y);
        System.out.println();

        double d1 = 764;
        double d2 = 55;
        System.out.println(d1+d2);
        System.out.println(d1*d2);
        System.out.println(d1/d2);
    }
}
