public class basicLoop {
    public static void main(String[] args) {
        int n = 10;
        for(int i=1; i<=n; i++){
            System.out.println("Radhe Radhe");
        }

        
        int i=1;
        while(i <= n){
            System.out.println("Shree krishna");
            i++;
        }
    }
}
